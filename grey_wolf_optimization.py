import numpy as np
import matplotlib.pyplot as plt

# --- Environment Setup ---
START = np.array([0.0, 0.0])
GOAL = np.array([10.0, 10.0])
NUM_WAYPOINTS = 8  # Number of internal nodes in the path

# Obstacles represented as (x, y, radius)
OBSTACLES = [
    (3.0, 3.0, 1.5),
    (5.0, 6.0, 2.0),
    (7.0, 4.0, 1.5)
]

# --- GWO Parameters ---
POP_SIZE = 50
MAX_ITER = 100
DIM = NUM_WAYPOINTS * 2  # Each waypoint has (x, y) coordinates

# Boundaries for waypoints
X_MIN, X_MAX = 0.0, 10.0
Y_MIN, Y_MAX = 0.0, 10.0

def reconstruct_path(decision_variables):
    """Converts a flat 1D array of decision variables back into a 2D path."""
    waypoints = decision_variables.reshape((NUM_WAYPOINTS, 2))
    # Complete path goes from START -> waypoints -> GOAL
    path = np.vstack([START, waypoints, GOAL])
    return path

def is_segment_intersecting_obstacle(p1, p2, obs_center, obs_radius):
    """Checks if a line segment between p1 and p2 intersects a circular obstacle."""
    d = p2 - p1
    f = p1 - obs_center
    a = np.dot(d, d)
    if a == 0:
        return np.linalg.norm(p1 - obs_center) < obs_radius

    b = 2 * np.dot(f, d)
    c = np.dot(f, f) - obs_radius**2
    discriminant = b**2 - 4*a*c
    if discriminant < 0:
        return False

    discriminant = np.sqrt(discriminant)
    t1 = (-b - discriminant) / (2*a)
    t2 = (-b + discriminant) / (2*a)

    if (t1 >= 0 and t1 <= 1) or (t2 >= 0 and t2 <= 1):
        return True
    if t1 < 0 and t2 > 1:
        return True
    return False

def fitness_function(decision_variables):
    """Calculates path length and adds a severe penalty for obstacle collision."""
    path = reconstruct_path(decision_variables)
    length = 0.0
    penalty = 0.0

    for i in range(len(path) - 1):
        p1, p2 = path[i], path[i+1]
        # Add Euclidean distance between consecutive waypoints
        length += np.linalg.norm(p2 - p1)

        # Check for collisions with each obstacle
        for obs in OBSTACLES:
            obs_center = np.array([obs[0], obs[1]])
            obs_radius = obs[2]
            if is_segment_intersecting_obstacle(p1, p2, obs_center, obs_radius):
                penalty += 1000.0  # Large constant penalty

    return length + penalty

# Initialize population within boundaries
Positions = np.random.uniform(low=X_MIN, high=X_MAX, size=(POP_SIZE, DIM))

# Initialize Alpha, Beta, and Delta wolves
Alpha_pos = np.zeros(DIM)
Alpha_score = float("inf")

Beta_pos = np.zeros(DIM)
Beta_score = float("inf")

Delta_pos = np.zeros(DIM)
Delta_score = float("inf")

# --- Optimization Loop ---
for l in range(MAX_ITER):
    for i in range(POP_SIZE):
        # Clip to boundaries
        Positions[i] = np.clip(Positions[i], X_MIN, X_MAX)

        # Calculate objective function for each search agent
        fitness = fitness_function(Positions[i])

        # Update Alpha, Beta, and Delta
        if fitness < Alpha_score:
            Alpha_score = fitness
            Alpha_pos = Positions[i].copy()

        if fitness > Alpha_score and fitness < Beta_score:
            Beta_score = fitness
            Beta_pos = Positions[i].copy()

        if fitness > Alpha_score and fitness > Beta_score and fitness < Delta_score:
            Delta_score = fitness
            Delta_pos = Positions[i].copy()

    a = 2 - l * (2 / MAX_ITER)  # 'a' decreases linearly from 2 to 0

    # Update the Position of search agents
    for i in range(POP_SIZE):
        for j in range(DIM):
            # Alpha update
            r1, r2 = np.random.random(), np.random.random()
            A1 = 2 * a * r1 - a
            C1 = 2 * r2
            D_alpha = abs(C1 * Alpha_pos[j] - Positions[i, j])
            X1 = Alpha_pos[j] - A1 * D_alpha

            # Beta update
            r1, r2 = np.random.random(), np.random.random()
            A2 = 2 * a * r1 - a
            C2 = 2 * r2
            D_beta = abs(C2 * Beta_pos[j] - Positions[i, j])
            X2 = Beta_pos[j] - A2 * D_beta

            # Delta update
            r1, r2 = np.random.random(), np.random.random()
            A3 = 2 * a * r1 - a
            C3 = 2 * r2
            D_delta = abs(C3 * Delta_pos[j] - Positions[i, j])
            X3 = Delta_pos[j] - A3 * D_delta

            # Average of leadership positions
            Positions[i, j] = (X1 + X2 + X3) / 3

