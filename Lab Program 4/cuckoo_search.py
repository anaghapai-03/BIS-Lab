import numpy as np

# 1. Define Warehouse Order Pricing Cost Function (to minimize)
def cost_function(prices):
    # Example: prices for 3 order categories.
    # We want to find prices that maximize revenue while keeping demand realistic (penalizing extremely high/low prices)
    base_demand = np.array([100, 150, 80])
    sensitivity = np.array([0.5, 0.7, 0.4])
    handling_cost = np.array([10, 15, 12])

    # Demand decreases as price increases
    demand = np.clip(base_demand - sensitivity * prices, 0, None)
    revenue = np.sum(prices * demand)
    cost = np.sum(handling_cost * demand)
    profit = revenue - cost
    return -profit  # Negative profit for minimization

# 2. Cuckoo Search Algorithm (Short Version)
def cuckoo_search(cost_func, num_parameters=3, num_nests=15, max_iter=100, pa=0.25):
    # Lower and upper bounds for prices
    lb, ub = 10.0, 100.0

    # Initialize nests (solutions)
    nests = np.random.uniform(lb, ub, (num_nests, num_parameters))
    fitness = np.array([cost_func(n) for n in nests])

    best_nest = nests[np.argmin(fitness)]
    best_fitness = np.min(fitness)

    for _ in range(max_iter):
        # Levy flight (new solution generation)
        for i in range(num_nests):
            # Simulating Levy flight step using normal distributions
            step = np.random.normal(0, 1, num_parameters) * 0.1
            new_nest = np.clip(nests[i] + step * (nests[i] - best_nest), lb, ub)
            new_fit = cost_func(new_nest)

            # Greedy selection
            random_index = np.random.randint(0, num_nests)
            if new_fit < fitness[random_index]:
                nests[random_index] = new_nest
                fitness[random_index] = new_fit

        # Abandon fraction (pa) of worst nests
        abandon_indices = np.argsort(fitness)[-int(pa * num_nests):]
        for idx in abandon_indices:
            nests[idx] = np.random.uniform(lb, ub, num_parameters)
            fitness[idx] = cost_func(nests[idx])

        # Track best
        current_best_idx = np.argmin(fitness)
        if fitness[current_best_idx] < best_fitness:
            best_fitness = fitness[current_best_idx]
            best_nest = nests[current_best_idx]

    return best_nest, -best_fitness

# Run the optimization
best_prices, max_profit = cuckoo_search(cost_function)
print(f"Optimized Pricing for Order Categories: {np.round(best_prices, 2)}")
print(f"Estimated Maximum Profit: ${max_profit:.2f}")
