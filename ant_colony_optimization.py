import random

roads = {
    "A": {"B": 4, "C": 2},
    "B": {"A": 4, "D": 5, "E": 2},
    "C": {"A": 2, "D": 8, "E": 3},
    "D": {"B": 5, "C": 8, "F": 2},
    "E": {"B": 2, "C": 3, "F": 4},
    "F": {"D": 2, "E": 4}
}
available_nodes = sorted(list(roads.keys()))
print(f"Available locations in the network: {', '.join(available_nodes)}")

start = input(f"Enter start node : ").strip().upper() or "A"
if start not in roads:
    print(f"Invalid node. Defaulting to 'A'")
    start = "A"

goal = input(f"Enter destination node : ").strip().upper() or "F"
if goal not in roads:
    print(f"Invalid node. Defaulting to 'F'")
    goal = "F"

try:
    num_ants = int(input("Enter number of ants: ") or "10")
    iterations = int(input("Enter number of iterations : ") or "50")
except ValueError:
    print("Invalid numeric input. Using defaults (10 ants, 50 iterations).")
    num_ants = 10
    iterations = 50

alpha = 1.0
beta = 2.0
rho = 0.5
Q = 100

pheromone = {}
for i in roads:
    for j in roads[i]:
        pheromone[(i, j)] = 1.0

def build_route():
    current = start
    route = [current]
    visited = {current}
    total_time = 0

    while current != goal:
        candidates = []

        for nxt, time in roads[current].items():
            if nxt not in visited:
                tau = pheromone[(current, nxt)]
                eta = 1 / time

                weight = (tau ** alpha) * (eta ** beta)
                candidates.append((nxt, time, weight))

        if not candidates:
            return None, float("inf")

        total_weight = sum(item[2] for item in candidates)
        probabilities = [
            item[2] / total_weight for item in candidates
        ]

        selected = random.choices(
            candidates, weights=probabilities, k=1
        )[0]

        nxt, time, _ = selected
        route.append(nxt)
        visited.add(nxt)
        total_time += time
        current = nxt

    return route, total_time

best_route = None
best_time = float("inf")

for iteration in range(iterations):
    ant_solutions = []

    for ant in range(num_ants):
        route, travel_time = build_route()

        if route is not None:
            ant_solutions.append((route, travel_time))

            if travel_time < best_time:
                best_route = route
                best_time = travel_time

    for edge in pheromone:
        pheromone[edge] *= (1 - rho)

    for route, travel_time in ant_solutions:
        deposit = Q / travel_time

        for i in range(len(route) - 1):
            edge = (route[i], route[i + 1])
            pheromone[edge] += deposit

            reverse_edge = (route[i + 1], route[i])
            pheromone[reverse_edge] += deposit

if best_route:
    print("\n--- Optimization Results ---")
    print("Best route:", " -> ".join(best_route))
    print("Estimated travel time:", best_time, "minutes")
else:
    print(f"\nNo route could be found between {start} and {goal} with the current parameters.")